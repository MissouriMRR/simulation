"""Vehicle designs: the model behind the Vehicles tab (no tkinter, so it can be tested without a window).

A design is a Project AirSim robot config. `Design` holds one as a plain dict and edits it as *blocks*: the vehicle's
own settings, the controller, and lists of links, joints, actuators and sensors. Every edit can be undone. `issues()`
checks the design against the settings catalog (vehicle_schema.py) and against itself (names unique, references
resolve, ArduPilot has the IMU it needs). `Library` is the folder of saved designs: create, rename, duplicate,
delete, with file-name rules, next to the read-only provided vehicles of sim_config.

Saving writes ordinary .jsonc: Project AirSim reads it directly and so does the scene generator. Comments are not
kept (the file is re-written from the data) except for a one-line header.
"""
from __future__ import annotations

import copy
import json
import os
import re
from dataclasses import dataclass
from pathlib import Path
from typing import Any

from ..scene import camerastream, scenecheck
from . import vehicle_schema as vs

SUFFIX = ".jsonc"
HEADER = "// MRRSimulator vehicle design (a Project AirSim robot config). Edit it in the Vehicles tab of the MRRSimulator window.\n"
MAX_NAME = 60
RESERVED = {"con", "prn", "aux", "nul", *(f"com{i}" for i in range(1, 10)), *(f"lpt{i}" for i in range(1, 10))}
STRUCTURE = ("links", "joints", "controller", "actuators", "sensors")  # how a vehicle is arranged, not settings of it
GENERATED_MARKER = "GENERATED by mrrsim scenegen"  # scenegen's own files are not vehicles to edit


class DesignError(ValueError):
    pass


# ------------------------------------------------------------------------------------------------ names
def check_name(name: str) -> str:
    """A design's name, cleaned; DesignError says what is wrong. The name is also the file name, so it must be one
    Windows accepts."""
    clean = " ".join(name.split())
    if not clean:
        raise DesignError("Give the design a name.")
    if len(clean) > MAX_NAME:
        raise DesignError(f"The name is longer than {MAX_NAME} characters.")
    if not re.fullmatch(r"[A-Za-z0-9 _.()\-]+", clean):
        raise DesignError("Use letters, numbers, spaces and _ - . ( ) in the name.")
    if clean[0] in ". " or clean[-1] in ". ":
        raise DesignError("The name cannot start or end with a dot.")
    if clean.split(".")[0].strip().lower() in RESERVED:
        raise DesignError(f"{clean!r} is a reserved name in Windows.")
    return clean


def slug(name: str) -> str:
    """The name as it appears in generated file names: lower case, letters, digits and underscores."""
    return re.sub(r"[^a-z0-9]+", "_", name.lower()).strip("_")[:40] or "design"


@dataclass(frozen=True)
class BlockRef:
    section: str       # "vehicle", "controller", "links", "joints", "actuators" or "sensors"
    index: int = 0     # position in a list section; 0 for the vehicle and the controller

    @property
    def single(self) -> bool:
        return self.section in ("vehicle", "controller")


@dataclass(frozen=True)
class Issue:
    level: str                      # "error" (will not work), "warning" (probably not what you mean), "info"
    message: str
    ref: BlockRef | None = None     # the block it is about
    path: tuple = ()                # the setting inside the block

    def __str__(self) -> str:
        return f"[{self.level}] {self.message}"


# ------------------------------------------------------------------------------------- reading values
def parse_value(setting: vs.Setting, text: str) -> Any:
    """What a field's text means for a setting: the JSON value, or None for 'leave it out'. DesignError if the text
    is not valid for the setting's kind."""
    text = text.strip()
    if text == "":
        return None
    kind = setting.kind
    if kind == vs.NUMBER:
        try:
            value = float(text)
        except ValueError:
            raise DesignError(f"{setting.title}: {text!r} is not a number.") from None
        return int(value) if value.is_integer() and "." not in text and "e" not in text.lower() else value
    if kind == vs.INTEGER:
        try:
            value = float(text)
        except ValueError:
            raise DesignError(f"{setting.title}: {text!r} is not a whole number.") from None
        if not value.is_integer():
            raise DesignError(f"{setting.title}: {text!r} is not a whole number.")
        return int(value)
    if kind in (vs.VEC3, vs.VEC4):
        parts = text.replace(",", " ").split()
        count = 3 if kind == vs.VEC3 else 4
        try:
            [float(p) for p in parts]
        except ValueError:
            raise DesignError(f"{setting.title}: needs {count} numbers, like '0 0 -1'.") from None
        if len(parts) != count:
            raise DesignError(f"{setting.title}: needs {count} numbers, like '0 0 -1'.")
        return " ".join(parts)
    if kind == vs.BOOL:
        if text.lower() in ("true", "yes", "1", "on"):
            return True
        if text.lower() in ("false", "no", "0", "off"):
            return False
        raise DesignError(f"{setting.title}: use true or false.")
    if kind == vs.ENUM:
        for choice in setting.choices:
            value, label = choice if isinstance(choice, tuple) else (choice, str(choice))
            if text == str(value) or text == label:
                return value
        raise DesignError(f"{setting.title}: pick one of the listed values.")
    if kind == vs.JSON:
        try:
            return json.loads(text)
        except ValueError as exc:
            raise DesignError(f"{setting.title}: not valid JSON ({exc}).") from None
    return text


def format_value(setting: vs.Setting, value: Any) -> str:
    """A setting's value as the text a field shows."""
    if value is None:
        return ""
    if isinstance(value, bool):
        return "true" if value else "false"
    if setting.kind == vs.ENUM:
        for choice in setting.choices:
            v, label = choice if isinstance(choice, tuple) else (choice, str(choice))
            if v == value:
                return label
    if isinstance(value, float):
        return f"{value:.10g}"
    return str(value)


def default_text(setting: vs.Setting) -> str:
    return "" if setting.default is None else format_value(setting, setting.default)


def _is_number(value: Any) -> bool:
    return isinstance(value, (int, float)) and not isinstance(value, bool)


# ------------------------------------------------------------------------------------------------ Design
class Design:
    """One vehicle design being edited."""

    def __init__(self, doc: dict, *, name: str = "", path: Path | None = None, provided: bool = False) -> None:
        self.doc: dict = doc
        self.name, self.path, self.provided = name, path, provided
        self._history: list[str] = [self._snapshot()]
        self._position = 0
        self._saved = self._history[0]

    # -------------------------------------------------------------------------------- history / state
    def _snapshot(self) -> str:
        return json.dumps(self.doc, sort_keys=False)

    @property
    def dirty(self) -> bool:
        return self._snapshot() != self._saved

    def mark_saved(self) -> None:
        self._saved = self._snapshot()

    def _writable(self) -> None:
        if self.provided:
            raise DesignError("This is a provided vehicle and is read-only. Duplicate it to make your own copy.")

    def _commit(self) -> None:
        snap = self._snapshot()
        if snap == self._history[self._position]:
            return
        del self._history[self._position + 1:]
        self._history.append(snap)
        self._position += 1

    @property
    def can_undo(self) -> bool:
        return self._position > 0

    @property
    def can_redo(self) -> bool:
        return self._position < len(self._history) - 1

    def undo(self) -> None:
        if self.can_undo:
            self._position -= 1
            self.doc = json.loads(self._history[self._position])

    def redo(self) -> None:
        if self.can_redo:
            self._position += 1
            self.doc = json.loads(self._history[self._position])

    def replace_document(self, doc: dict) -> None:
        """Swap the whole design (the raw JSON editor); one undo step."""
        self._writable()
        if not isinstance(doc, dict):
            raise DesignError("A vehicle design is a JSON object.")
        self.doc = doc
        self._commit()

    # --------------------------------------------------------------------------------------- blocks
    def count(self, section: str) -> int:
        return len(self.doc.get(section) or []) if section in vs.LIST_SECTIONS else 1

    def blocks(self, section: str | None = None) -> list[BlockRef]:
        sections = (section,) if section else vs.SECTION_ORDER
        out: list[BlockRef] = []
        for sec in sections:
            if sec == "vehicle":
                out.append(BlockRef("vehicle"))
            elif sec == "controller":
                if isinstance(self.doc.get("controller"), dict):
                    out.append(BlockRef("controller"))
            else:
                out += [BlockRef(sec, i) for i, item in enumerate(self.doc.get(sec) or []) if isinstance(item, dict)]
        return out

    def get(self, ref: BlockRef) -> dict:
        if ref.section == "vehicle":
            return self.doc
        if ref.section == "controller":
            return self.doc.setdefault("controller", {})
        try:
            return self.doc[ref.section][ref.index]
        except (KeyError, IndexError, TypeError):
            raise DesignError(f"There is no {ref.section[:-1]} number {ref.index + 1}.") from None

    def block_type(self, ref: BlockRef) -> vs.BlockType | None:
        return vs.block_type(ref.section, str(self.get(ref).get("type", "")))

    def legacy_count(self) -> int:
        """How many keys Fix spellings would rename (found on a copy; the design is not changed)."""
        return Design(copy.deepcopy(self.doc)).fix_legacy()

    def name_of(self, ref: BlockRef) -> str:
        if ref.section == "vehicle":
            return "Vehicle"
        bt = self.block_type(ref)
        return str(self.get(ref).get(bt.name_key if bt else "id", self.get(ref).get("name", "")))

    def label(self, ref: BlockRef) -> str:
        bt = self.block_type(ref)
        title = bt.title if bt else ref.section[:-1].capitalize()
        if ref.section == "vehicle":
            return title
        return f"{title} \"{self.name_of(ref)}\"" if self.name_of(ref) else title

    def names(self, section: str) -> list[str]:
        """The names of the blocks of a section (links, joints, actuators or sensors)."""
        key = "name" if section in ("links", "actuators") else "id"
        return [str(i.get(key, "")) for i in self.doc.get(section) or [] if isinstance(i, dict)]

    def find(self, section: str, name: str) -> BlockRef | None:
        for ref in self.blocks(section):
            if self.name_of(ref) == name:
                return ref
        return None

    def unique_name(self, section: str, base: str) -> str:
        taken = set(self.names(section))
        if base not in taken:
            return base
        n = 2
        while f"{base}{n}" in taken:
            n += 1
        return f"{base}{n}"

    # ------------------------------------------------------------------------------ editing values
    @staticmethod
    def _walk(obj: Any, path: tuple, create: bool) -> Any:
        for step in path:
            if isinstance(step, int):
                obj = obj[step]
            else:
                if create:
                    obj = obj.setdefault(step, {})
                else:
                    obj = obj[step]
        return obj

    def get_value(self, ref: BlockRef, path: tuple, default: Any = None) -> Any:
        try:
            parent = self._walk(self.get(ref), path[:-1], False)
            step = path[-1]
            return parent[step] if isinstance(step, int) or step in parent else default
        except (KeyError, IndexError, TypeError):
            return default

    def set_value(self, ref: BlockRef, path: tuple, value: Any) -> None:
        """Set the setting at `path` (keys and list indices below the block) to `value`; None removes it."""
        self._writable()
        if value is None:
            return self.remove_value(ref, path)
        try:
            parent = self._walk(self.get(ref), path[:-1], True)
            step = path[-1]
            if isinstance(step, int):
                parent[step] = value
            else:
                if parent.get(step) == value and type(parent.get(step)) is type(value):
                    return
                parent[step] = value
        except (TypeError, IndexError, KeyError, AttributeError):
            raise DesignError("Part of this setting is stored as something other than an object or list in the file; "
                              "fix it in the JSON editor first.") from None
        self._commit()

    def remove_value(self, ref: BlockRef, path: tuple) -> None:
        self._writable()
        block = self.get(ref)
        try:
            parent = self._walk(block, path[:-1], False)
            step = path[-1]
            if isinstance(step, int):
                del parent[step]
            elif step in parent:
                del parent[step]
            else:
                return
            # a group left with nothing in it is removed too ({} would read as "present but empty")
            for depth in range(len(path) - 1, 0, -1):
                container = self._walk(block, path[:depth], False)
                above = self._walk(block, path[:depth - 1], False)
                if isinstance(container, dict) and not container and isinstance(above, dict):
                    del above[path[depth - 1]]
                else:
                    break
        except (KeyError, IndexError, TypeError):
            return
        self._commit()

    def append_row(self, ref: BlockRef, path: tuple, row: dict) -> int:
        """Add a row to a table setting (a capture, a mask ...); returns its index."""
        self._writable()
        parent = self._walk(self.get(ref), path[:-1], True)
        rows = parent.setdefault(path[-1], [])
        rows.append(copy.deepcopy(row))
        self._commit()
        return len(rows) - 1

    # ---------------------------------------------------------------------------- adding / removing
    def add_block(self, bt: vs.BlockType, *, name: str | None = None, parent_link: str | None = None) -> BlockRef:
        """Put a new block of this type on the vehicle. A sensor or actuator is attached to `parent_link`, or to the first link."""
        self._writable()
        if bt.section == "vehicle":
            raise DesignError("The vehicle itself is always there.")
        if bt.section == "controller":
            return self.set_controller_type(bt.template.get("type", "ardupilot-api"))
        item = copy.deepcopy(bt.template)
        base = name or str(item.get(bt.name_key) or bt.title)
        item[bt.name_key] = self.unique_name(bt.section, base)
        links = self.names("links")
        if "parent-link" in item and bt.section in ("sensors", "actuators"):
            item["parent-link"] = parent_link if parent_link is not None else (links[0] if links else "")
        self.doc.setdefault(bt.section, []).append(item)
        self._commit()
        return BlockRef(bt.section, len(self.doc[bt.section]) - 1)

    def set_controller_type(self, type_name: str) -> BlockRef:
        """Replace the controller with a fresh one of this type (keeping its name)."""
        self._writable()
        if type_name not in vs.CONTROLLER.setting("type").choice_values():
            raise DesignError(f"Unknown controller type {type_name!r}.")
        old = self.doc.get("controller") or {}
        controller = {"id": old.get("id") or "Controller", "type": type_name}
        settings_key = next((s.key for s in vs.CONTROLLER.settings if s.when and type_name in s.when[1] and s.kind == vs.GROUP), None)
        if settings_key:
            controller[settings_key] = {"actuator-order": [{"id": n} for n in self._rotor_names()]}
            if type_name == "ardupilot-api":
                controller[settings_key].update({"ardupilot-ip": "127.0.0.1", "ardupilot-udp-port": 9003,
                                                 "local-host-ip": "127.0.0.1", "local-host-udp-port": 9002})
        if type_name == "simple-flight-api":
            controller["airframe-setup"] = "quadrotor-x"
        self.doc["controller"] = controller
        self._commit()
        return BlockRef("controller")

    def _rotor_names(self) -> list[str]:
        return [n for n, a in zip(self.names("actuators"), self.doc.get("actuators") or []) if a.get("type") == "rotor"]

    def references_to(self, ref: BlockRef) -> list[str]:
        """Who points at this block: a description of each part that names a link or an actuator."""
        if ref.section not in ("links", "actuators"):
            return []
        name = self.name_of(ref)
        out: list[str] = []
        for sec in ("sensors", "actuators", "joints", "links"):
            for other in self.blocks(sec):
                if other == ref:
                    continue
                item = self.get(other)
                if ref.section == "links" and name in (item.get("parent-link"), item.get("child-link")):
                    out.append(self.label(other))
                if ref.section == "actuators" and sec == "actuators" and item.get("tilt-settings", {}).get("target") == name:
                    out.append(self.label(other))
        if ref.section == "actuators":
            controller = self.doc.get("controller") or {}
            for settings in controller.values():
                if isinstance(settings, dict) and any(e.get("id") == name for e in settings.get("actuator-order") or [] if isinstance(e, dict)):
                    out.append("the controller's actuator order")
                    break
        return out

    def remove_block(self, ref: BlockRef) -> None:
        """Take a block off the vehicle. Parts that were attached to a removed link are left unattached; a removed
        actuator leaves the controller's actuator order."""
        self._writable()
        if ref.single:
            raise DesignError("The vehicle and its controller cannot be removed (replace the controller instead).")
        name = self.name_of(ref)
        del self.doc[ref.section][ref.index]
        if ref.section == "links":
            for sec in ("sensors", "actuators", "joints"):
                for item in self.doc.get(sec) or []:
                    for key in ("parent-link", "child-link"):
                        if item.get(key) == name:
                            item[key] = ""
        if ref.section == "actuators":
            for settings in (self.doc.get("controller") or {}).values():
                if isinstance(settings, dict) and isinstance(settings.get("actuator-order"), list):
                    settings["actuator-order"] = [e for e in settings["actuator-order"]
                                                  if not (isinstance(e, dict) and e.get("id") == name)]
        self._commit()

    def duplicate_block(self, ref: BlockRef) -> BlockRef:
        self._writable()
        if ref.single:
            raise DesignError("The vehicle and its controller cannot be duplicated.")
        item = copy.deepcopy(self.get(ref))
        key = "name" if ref.section in ("links", "actuators") else "id"
        item[key] = self.unique_name(ref.section, f"{item.get(key, 'Copy')}Copy")
        self.doc[ref.section].insert(ref.index + 1, item)
        self._commit()
        return BlockRef(ref.section, ref.index + 1)

    def move_block(self, ref: BlockRef, delta: int) -> BlockRef:
        """Reorder within the section (the order of actuators does not matter; the controller's actuator order does)."""
        self._writable()
        if ref.single:
            return ref
        items = self.doc[ref.section]
        target = ref.index + delta
        if not 0 <= target < len(items):
            return ref
        items[ref.index], items[target] = items[target], items[ref.index]
        self._commit()
        return BlockRef(ref.section, target)

    def rename_block(self, ref: BlockRef, new_name: str) -> None:
        """Rename a block and everything that refers to it by name."""
        self._writable()
        if ref.single:
            raise DesignError("The vehicle and its controller keep their names; change the controller's name in its settings.")
        new = new_name.strip()
        if not new:
            raise DesignError("The name cannot be empty.")
        old = self.name_of(ref)
        if new == old:
            return
        if new in self.names(ref.section):
            raise DesignError(f"There is already a {ref.section[:-1]} called {new!r}.")
        self.get(ref)["name" if ref.section in ("links", "actuators") else "id"] = new
        if ref.section == "links":
            for sec in ("sensors", "actuators", "joints", "links"):
                for item in self.doc.get(sec) or []:
                    for key in ("parent-link", "child-link"):
                        if item.get(key) == old:
                            item[key] = new
        elif ref.section == "actuators":
            for item in self.doc.get("actuators") or []:
                tilt = item.get("tilt-settings")
                if isinstance(tilt, dict) and tilt.get("target") == old:
                    tilt["target"] = new
            for settings in (self.doc.get("controller") or {}).values():
                if isinstance(settings, dict):
                    for entry in settings.get("actuator-order") or []:
                        if isinstance(entry, dict) and entry.get("id") == old:
                            entry["id"] = new
        self._commit()

    # ------------------------------------------------------------------------------------- legacy keys
    def fix_legacy(self) -> int:
        """Rename keys the docs/schema spell differently from the code to what the simulator reads. Returns how many."""
        self._writable()
        fixed = 0

        def fix(obj: dict, settings: tuple[vs.Setting, ...]) -> None:
            nonlocal fixed
            for s in settings:
                for old in s.legacy:
                    if s.kind != vs.ENUM and old in obj and s.key not in obj:
                        obj[s.key] = obj.pop(old)
                        fixed += 1
                if s.kind == vs.ENUM and s.legacy and obj.get(s.key) in s.legacy:
                    obj[s.key] = str(obj[s.key]).replace("-", "_")
                    fixed += 1
                value = obj.get(s.key)
                if s.kind == vs.GROUP and isinstance(value, dict):
                    fix(value, s.children)
                elif s.kind == vs.TABLE and isinstance(value, list):
                    for row in value:
                        if isinstance(row, dict):
                            fix(row, s.children)
        for ref in self.blocks():
            bt = self.block_type(ref)
            if bt:
                fix(self.get(ref), bt.settings)
        if fixed:
            self._commit()
        return fixed

    # ---------------------------------------------------------------------------------- saving
    def dumps(self) -> str:
        return HEADER + json.dumps(self.doc, indent=2) + "\n"

    def airsim_json(self) -> str:
        """The robot config as Project AirSim reads it: this design without the launcher's own settings (the camera's
        picture stream), as plain JSON that can be pasted into a robot config file. The ArduPilot UDP ports are the
        ones of vehicle 0; the launcher gives every further vehicle its own."""
        return json.dumps(camerastream.strip(self.doc), indent=2) + "\n"

    # --------------------------------------------------------------------------------- validation
    def issues(self) -> list[Issue]:
        return validate(self)

    def runnable_problem(self) -> str:
        """Why this design cannot fly with this launcher's ArduPilot SITL, or "" if it can."""
        return runnable_problem(self.doc)


def runnable_problem(doc: dict) -> str:
    controller = doc.get("controller")
    if not isinstance(controller, dict) or controller.get("type") != "ardupilot-api":
        return "its controller is not ArduPilot (ardupilot-api); the simulator's flight controllers are ArduPilot SITL containers"
    settings = controller.get("ardupilot-settings")
    if not isinstance(settings, dict) or not all(isinstance(settings.get(k), int) for k in ("ardupilot-udp-port", "local-host-udp-port")):
        return "its ArduPilot controller has no UDP ports"
    if not any(isinstance(s, dict) and s.get("type") == "imu" and s.get("enabled", True) for s in doc.get("sensors") or []):
        return "it has no enabled IMU, which ArduPilot needs"
    return ""


# ------------------------------------------------------------------------------------------ validation
def _check_setting(issues: list[Issue], ref: BlockRef | None, bt_title: str, path: tuple, s: vs.Setting, value: Any,
                   design: Design) -> None:
    def add(level: str, message: str) -> None:
        issues.append(Issue(level, f"{bt_title}: {'.'.join(str(p) for p in path)}: {message}" if path else message, ref, path))

    kind = s.kind
    if kind == vs.NUMBER or kind == vs.INTEGER:
        if not _is_number(value):
            return add("error", "must be a number.")
        if kind == vs.INTEGER and float(value) != int(value):
            return add("error", "must be a whole number.")
        if s.minimum is not None and value < s.minimum:
            add("warning", f"{value} is below the usual minimum of {s.minimum:g}.")
        if s.maximum is not None and value > s.maximum:
            add("warning", f"{value} is above the usual maximum of {s.maximum:g}.")
    elif kind == vs.BOOL:
        if not (isinstance(value, bool) or value in (0, 1)):
            add("error", "must be true or false.")
    elif kind in (vs.STRING, vs.LINKREF, vs.ACTREF):
        if not isinstance(value, str):
            return add("error", "must be text.")
        if kind == vs.LINKREF and value and value not in design.names("links"):
            add("error", f"there is no link called {value!r}.")
        if kind == vs.ACTREF and value and value not in design.names("actuators"):
            add("error", f"there is no actuator called {value!r}.")
    elif kind == vs.ENUM:
        if value in s.choice_values():
            return
        if isinstance(value, str) and value in s.legacy:
            return add("warning", f"{value!r} is how the docs spell it; the simulator only accepts {value.replace('-', '_')!r}.")
        add("error", f"{value!r} is not one of {', '.join(str(v) for v in s.choice_values())}.")
    elif kind in (vs.VEC3, vs.VEC4):
        count = 3 if kind == vs.VEC3 else 4
        if not (isinstance(value, str) and len(value.replace(",", " ").split()) == count
                and all(_looks_numeric(p) for p in value.replace(",", " ").split())):
            add("error", f"must be {count} numbers separated by spaces.")
    elif kind == vs.GROUP:
        if not isinstance(value, dict):
            return add("error", "must be an object.")
        _check_object(issues, ref, bt_title, path, s.children, value, design)
    elif kind == vs.TABLE:
        if not isinstance(value, list):
            return add("error", "must be a list.")
        for i, row in enumerate(value):
            if not isinstance(row, dict):
                add("error", f"entry {i + 1} must be an object.")
            else:
                _check_object(issues, ref, bt_title, path + (i,), s.children, row, design)
    elif kind == vs.LIST:
        if not isinstance(value, list) or not all(isinstance(v, str) for v in value):
            add("error", "must be a list of text values.")
    elif kind == vs.MAP:
        if not isinstance(value, dict) or not all(_is_number(v) for v in value.values()):
            add("error", "must be a table of name -> number.")


def _looks_numeric(text: str) -> bool:
    try:
        float(text)
        return True
    except ValueError:
        return False


def _check_object(issues: list[Issue], ref: BlockRef | None, title: str, path: tuple,
                  settings: tuple[vs.Setting, ...], obj: dict, design: Design) -> None:
    known: set[str] = set()
    for s in settings:
        known.add(s.key)
        known.update(s.aliases)
        present = [k for k in (s.key, *s.aliases) if k in obj]
        where = path + (s.key,)
        if s.ignored:
            if present:
                issues.append(Issue("warning", f"{title}: {'.'.join(map(str, where))}: {s.ignored}.", ref, where))
            continue
        if s.when and not sibling_in(s.when, obj, settings):
            continue
        if not present:
            if s.required and not (s.unless and sibling_in(s.unless, obj, settings)):
                issues.append(Issue("error", f"{title}: {'.'.join(map(str, where))}: required but missing.", ref, where))
            continue
        _check_setting(issues, ref, title, where, s, obj[present[0]], design)
    legacy = {old: s for s in settings for old in s.legacy if s.kind != vs.ENUM}
    for key in obj:
        if key in known or key == "type" or key.startswith("$"):
            continue
        if key in legacy:
            issues.append(Issue("warning", f"{title}: {'.'.join(map(str, path + (key,)))}: the simulator does not read "
                                           f"'{key}'; it reads '{legacy[key].key}'. Use Fix spellings to rename it.", ref, path + (key,)))
        else:
            issues.append(Issue("info", f"{title}: {'.'.join(map(str, path + (key,)))}: not a known setting; kept as it is "
                                        f"(the simulator ignores keys it does not know).", ref, path + (key,)))


def sibling_in(condition: tuple[str, tuple], obj: dict, settings: tuple[vs.Setting, ...]) -> bool:
    """Does the setting beside this one (named in the condition) have one of the listed values? A setting that is not
    set counts as having its catalog default."""
    key, values = condition
    if key in obj:
        return obj[key] in values
    sibling = next((x for x in settings if x.key == key), None)
    return sibling is not None and sibling.default in values


def validate(design: Design) -> list[Issue]:
    issues: list[Issue] = []
    doc = design.doc
    # blocks against the catalog
    for ref in design.blocks():
        item = design.get(ref)
        bt = design.block_type(ref)
        title = design.label(ref)
        if bt is None:
            issues.append(Issue("warning", f"{title}: unknown type {item.get('type')!r}; it is kept as it is and edited as JSON.", ref))
            continue
        if ref.section == "controller":
            _check_controller(issues, ref, item, bt, title, design)
        else:
            own = item if ref.section != "vehicle" else {k: v for k, v in item.items() if k not in STRUCTURE}
            _check_object(issues, ref, title, (), bt.settings, own, design)
    _check_camera_streams(issues, design)
    # names
    for section in vs.LIST_SECTIONS:
        names = design.names(section)
        for name in {n for n in names if names.count(n) > 1}:
            first = next(r for r in design.blocks(section) if design.name_of(r) == name)
            issues.append(Issue("error", f"There is more than one {section[:-1]} called {name!r}.", first))
        for ref in design.blocks(section):
            if not design.name_of(ref).strip():
                issues.append(Issue("error", f"A {section[:-1]} has no name.", ref))
    # structure
    if not isinstance(doc.get("controller"), dict) and doc.get("physics-type") in ("fast-physics", "matlab-physics", "jsbsim-physics"):
        issues.append(Issue("warning", "The vehicle has no controller, so nothing commands its actuators (fine for a vehicle that "
                                       "is moved by scripts or by Unreal).", BlockRef("controller")))
    needs_links = bool(doc.get("sensors")) or any(isinstance(a, dict) and a.get("type") != "unreal-vehicle"
                                                   for a in doc.get("actuators") or []) or bool(doc.get("joints"))
    if not design.names("links") and needs_links and doc.get("physics-type") == "fast-physics":
        issues.append(Issue("warning", "The vehicle has no links, so its sensors and actuators are attached to nothing."))
    if doc.get("unreal-vehicle-class") and doc.get("wheeled-vehicle-class"):
        issues.append(Issue("error", "Use either an Unreal vehicle class or a wheeled vehicle class, not both.", BlockRef("vehicle")))
    # ArduPilot readiness
    controller = doc.get("controller") if isinstance(doc.get("controller"), dict) else {}
    if controller.get("type") == "ardupilot-api":
        sensors = [s for s in doc.get("sensors") or [] if isinstance(s, dict) and s.get("enabled", True)]
        if not any(s.get("type") == "imu" for s in sensors):
            issues.append(Issue("error", "ArduPilot needs an enabled IMU sensor; without one the simulator refuses to start the vehicle.",
                                BlockRef("controller")))
        if not any(s.get("type") == "gps" for s in sensors):
            issues.append(Issue("warning", "There is no enabled GPS: ArduPilot gets no position fix and will not arm in GPS modes.",
                                BlockRef("controller")))
        rotors = design._rotor_names()
        order = [e.get("id") for e in (controller.get("ardupilot-settings") or {}).get("actuator-order") or [] if isinstance(e, dict)]
        if rotors and sorted(order) != sorted(rotors):
            repeated = sorted({n for n in order if order.count(n) > 1})
            unused = [n for n in rotors if n not in order]
            for name in repeated:
                issues.append(Issue("error", f"The ArduPilot actuator order lists {name!r} more than once: that rotor gets two "
                                             f"outputs, and another one gets none, so the vehicle cannot fly straight.", BlockRef("controller")))
            for name in unused:
                issues.append(Issue("error", f"The ArduPilot actuator order does not list the rotor {name!r}: it gets no power.",
                                    BlockRef("controller")))
            if not repeated and not unused:
                issues.append(Issue("warning", f"The ArduPilot actuator order lists {len(order)} actuator(s) but the vehicle has "
                                               f"{len(rotors)} rotor(s); ArduPilot sends one output per listed actuator.", BlockRef("controller")))
    why = runnable_problem(doc)
    if why:
        issues.append(Issue("info", f"This design cannot fly with the launcher's SITL setup: {why}."))
    return issues


def _check_camera_streams(issues: list[Issue], design: Design) -> None:
    for ref in design.blocks("sensors"):
        item = design.get(ref)
        group = item.get(camerastream.STREAM_KEY) if isinstance(item, dict) else None
        if not (isinstance(group, dict) and group.get("enabled") is True and item.get("type") == "camera"):
            continue
        title = design.label(ref)
        where = (camerastream.STREAM_KEY, "port")
        if item.get("enabled", True) is False:
            issues.append(Issue("info", f"{title}: the camera is switched off, so it sends no pictures.", ref, where))
            continue
        if not camerastream.capture_ok(item):
            types = dict(vs.IMAGE_TYPES)
            issues.append(Issue(
                "error", f"{title}: it is set to send {types.get(camerastream.setting(item, 'image-type'), 'a capture')} pictures to the "
                         f"script, but none of its captures of that type has 'Send images to scripts' on.", ref,
                (camerastream.STREAM_KEY, "image-type")))
        owner = camerastream.reserved_port(group.get("port", camerastream.DEFAULTS["port"]))
        if owner:
            issues.append(Issue("error", f"{title}: port {group.get('port')} is used by {owner}; pick another.", ref, where))


def _check_controller(issues: list[Issue], ref: BlockRef, item: dict, bt: vs.BlockType, title: str, design: Design) -> None:
    _check_object(issues, ref, title, (), bt.settings, item, design)
    for key, settings in item.items():
        if isinstance(settings, dict):
            for i, entry in enumerate(settings.get("actuator-order") or []):
                name = entry.get("id") if isinstance(entry, dict) else None
                if name and name not in design.names("actuators"):
                    issues.append(Issue("error", f"{title}: {key}.actuator-order[{i}]: there is no actuator called {name!r}.", ref,
                                        (key, "actuator-order", i, "id")))



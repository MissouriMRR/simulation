def _is_generated(path: Path) -> bool:
    try:
        return GENERATED_MARKER in path.read_text(encoding="utf-8", errors="replace")[:400]
    except OSError:
        return False


class Library:
    """The folder of saved designs, and the provided vehicles beside it (read-only)."""

    def __init__(self, folder: Path, provided_dir: Path | None = None) -> None:
        self.folder, self.provided_dir = folder, provided_dir

    # names
    def path_of(self, name: str) -> Path:
        return self.folder / f"{check_name(name)}{SUFFIX}"

    def names(self) -> list[str]:
        if not self.folder.is_dir():
            return []
        return sorted((p.stem for p in self.folder.glob(f"*{SUFFIX}") if p.is_file()), key=str.lower)

    def exists(self, name: str) -> bool:
        wanted = name.strip().lower()
        return any(n.lower() == wanted for n in self.names())

    def unique_name(self, base: str) -> str:
        base = check_name(base)
        if not self.exists(base):
            return base
        n = 2
        while self.exists(f"{base} {n}"):
            n += 1
        return f"{base} {n}"

    # provided vehicles
    def provided(self) -> list[Path]:
        """The robot configs shipped with the simulator (sim_config), without the generated copies."""
        if not self.provided_dir or not self.provided_dir.is_dir():
            return []
        found = []
        for p in sorted(self.provided_dir.glob(f"robot_*{SUFFIX}"), key=lambda q: q.name.lower()):
            if p.is_file() and not _is_generated(p):
                found.append(p)
        return found

    def load_provided(self, path: Path) -> Design:
        return Design(self._read(path), name=path.stem, path=path, provided=True)

    # reading and writing
    @staticmethod
    def _read(path: Path) -> dict:
        try:
            doc = scenecheck.load_jsonc(path)
        except scenecheck.SceneParseError as exc:
            raise DesignError(f"Could not read {path.name}: {exc}") from None
        if not isinstance(doc, dict):
            raise DesignError(f"{path.name} is not a vehicle design (a JSON object).")
        return doc

    def load(self, name: str) -> Design:
        path = self.path_of(name)
        if not path.is_file():
            raise DesignError(f"There is no design called {name!r}.")
        return Design(self._read(path), name=path.stem, path=path)

    def save(self, design: Design) -> None:
        if design.provided or design.path is None:
            raise DesignError("Save it under a name first (Duplicate a provided vehicle, or create a new design).")
        self.folder.mkdir(parents=True, exist_ok=True)
        tmp = design.path.with_name(design.path.name + ".tmp")
        tmp.write_text(design.dumps(), encoding="utf-8", newline="\n")
        os.replace(tmp, design.path)  # a half-written file never replaces a good one
        design.mark_saved()

    def create(self, name: str, doc: dict) -> Design:
        name = check_name(name)
        if self.exists(name):
            raise DesignError(f"There is already a design called {name!r}.")
        design = Design(copy.deepcopy(doc), name=name, path=self.path_of(name))
        self.save(design)
        return design

    def duplicate(self, source: Design, new_name: str) -> Design:
        return self.create(new_name, source.doc)

    def rename(self, old: str, new: str) -> str:
        new = check_name(new)
        old_path = self.path_of(old)
        if not old_path.is_file():
            raise DesignError(f"There is no design called {old!r}.")
        if new.lower() != old.strip().lower() and self.exists(new):
            raise DesignError(f"There is already a design called {new!r}.")
        new_path = self.path_of(new)
        chosen = self._selected_name()  # read before the file moves: afterwards the old name no longer exists
        if str(new_path) != str(old_path):  # (not Path equality: on Windows that ignores case)
            os.replace(old_path, new_path)  # also a case-only change of the name
        if chosen is not None and chosen.lower() == old.strip().lower():
            self.select(new)
        return new

    def delete(self, name: str) -> None:
        path = self.path_of(name)
        if not path.is_file():
            raise DesignError(f"There is no design called {name!r}.")
        path.unlink()
        if self.selected() == name:
            self.select(None)

    # which design runs
    def _selected_file(self) -> Path:
        return self.folder / ".selected"

    def _selected_name(self) -> str | None:
        try:
            return self._selected_file().read_text(encoding="utf-8").strip() or None
        except OSError:
            return None

    def selected(self) -> str | None:
        """The design the simulator is run with, or None for the provided vehicle."""
        name = self._selected_name()
        return name if name and self.exists(name) else None

    def select(self, name: str | None) -> None:
        self.folder.mkdir(parents=True, exist_ok=True)
        if name is None:
            self._selected_file().unlink(missing_ok=True)
        else:
            self._selected_file().write_text(check_name(name), encoding="utf-8")



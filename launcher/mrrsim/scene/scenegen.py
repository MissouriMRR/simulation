"""Generate a Project AirSim scene with N ArduPilot quadrotors from the single-vehicle scene.

The single-vehicle scene (`[scene] scene`) and its robot config stay the source of truth. For N vehicles
this writes, next to the originals:

    scene_ardupilot_<N>quadrotors.jsonc    Drone1..DroneN, spaced along +y, PER_ROW to a row
                                           (the next row starts one spacing along +x)
    <robot stem>_<k>.jsonc                 robot config for Drone<k> (k = 2..N), UDP ports of vehicle k-1

Vehicle 0 keeps the original robot config Generated files carry a GENERATED marker in a comment and are
overwritten on every run.

With a `design` (a vehicle made in the Vehicles tab: its slug and its robot-config dict) the design is the template
instead of the robot config named by the scene: every vehicle gets robot_design_<slug>[_<k>].jsonc, vehicle 0 included,
and the scene is scene_ardupilot_<N>quadrotors[...]_design_<slug>.jsonc.

With a `pose` (poseargs.py) the vehicles spawn where it says instead of at the scene's own origin, and the scene
name ends with the pose's tag: scene_ardupilot_<N>quadrotors[...]_pose<hash>.jsonc.
"""
from __future__ import annotations

import json
import re
from pathlib import Path
from typing import NamedTuple

from ..core import ports
from . import camerastream, poseargs, scenecheck

# === CONSTANTS ================================================================


MARKER = "GENERATED by mrrsim scenegen"
DEFAULT_SPACING_M = 5.0
PER_ROW = 10  # vehicles in a row before the next row starts (so 100 drones are a 10 x 10 block, not a 300 m line)

Size = tuple[int, int]  # width, height in pixels


class SceneGenError(ValueError):
    """The scene cannot be generated: a template that does not fit, a file that is not ours, a bad count."""


class _Template(NamedTuple):
    """The robot config the vehicles are made from."""

    name: str  # the file name that the vehicles' files are named after
    slug: str | None  # the vehicle design it comes from; None: the robot config of the scene
    text: str  # the config as written (a hand-written file keeps its comments)
    doc: dict  # the same, parsed


# === SMALL HELPERS ============================================================


def _dumps(doc: dict) -> str:
    """A JSON document as the text of a generated file."""
    return json.dumps(doc, indent=2) + "\n"


def _robot_actors(scene: dict) -> list[dict]:
    """The robots of a scene."""
    return [a for a in scene.get("actors", []) if a.get("type") == "robot"]


def _design_advice(slug: str) -> str:
    """What a generated file says about changing a file that comes from a vehicle design."""
    return f"Edit the vehicle design {slug!r} in the Vehicles tab and run again instead of editing this file."


# === NAMES ====================================================================


def variant_tag(cameras: bool, resized_to: Size | None) -> str:
    """What the generated file names say about how they differ from the originals."""
    if not cameras:
        return "_nocam"
    return f"_{resized_to[0]}x{resized_to[1]}" if resized_to else ""


def scene_name(count: int, cameras: bool = True, resized_to: Size | None = None, design_slug: str = "",
               pose: poseargs.Pose | None = None) -> str:
    """The file name of the generated scene for these choices."""
    design = f"_design_{design_slug}" if design_slug else ""
    placed = f"_{pose.tag()}" if pose else ""   # another pose is another file, so runs with different poses never overwrite
    return f"scene_ardupilot_{count}quadrotors{variant_tag(cameras, resized_to)}{design}{placed}.jsonc"


# === CAMERAS ==================================================================


def _feed_size(setting: dict) -> Size | None:
    """The width and height of a capture setting; None when it has none, or they are not whole numbers."""
    try:
        return int(setting["width"]), int(setting["height"])
    except (KeyError, TypeError, ValueError):
        return None


def streaming_sizes(robot: dict) -> set[Size]:
    """Sizes of the camera feeds Project AirSim streams to the simulator window."""
    return {
        size
        for sensor in robot.get("sensors", [])
        if sensor.get("type") == "camera" and sensor.get("enabled", True)
        for setting in sensor.get("capture-settings", [])
        if setting.get("streaming-enabled") and (size := _feed_size(setting)) is not None
    }


def display_resize_needed(config_dir: Path, scene_file: str, window: Size) -> bool:
    """Would loading this single-vehicle scene make Unreal resize its window?

    When a vehicle spawns, Unreal resizes its window to the size of the camera it streams (and, if its
    remembered mode was fullscreen, goes fullscreen with it). A window of the same size has nothing to
    change. Scenes that cannot be read, or that are not a single-robot template, say False."""
    try:
        scene = scenecheck.load_jsonc(config_dir / scene_file)
        robots = _robot_actors(scene)
        if len(robots) != 1:
            return False
        robot = scenecheck.load_jsonc(config_dir / robots[0].get("robot-config", ""))
    except (scenecheck.SceneParseError, OSError):
        return False
    return any(size != window for size in streaming_sizes(robot))


def _match_streaming(robot: dict, window: Size) -> dict:
    """Make every streamed camera feed the size of the simulator window."""
    for sensor in robot.get("sensors", []):
        if sensor.get("type") == "camera" and sensor.get("enabled", True):
            for setting in sensor.get("capture-settings", []):
                if setting.get("streaming-enabled"):
                    setting["width"], setting["height"] = window
    return robot


def _strip_cameras(robot: dict) -> dict:
    """Disable every camera sensor and its capture/streaming."""
    for sensor in robot.get("sensors", []):
        if sensor.get("type") == "camera":
            sensor["enabled"] = False
            for setting in sensor.get("capture-settings", []):
                setting["capture-enabled"] = False
                setting["streaming-enabled"] = False
    return robot


def _adapt_template(template: _Template, cameras: bool, window: Size | None) -> tuple[str, Size | None]:
    """The template's text as the vehicles get it (cameras off, or the streamed camera resized to the window), and
    the size it was resized to (None: not resized)."""
    if not cameras:
        return _dumps(_strip_cameras(template.doc)), None
    if window and any(size != window for size in streaming_sizes(template.doc)):
        return _dumps(_match_streaming(template.doc, window)), window
    return template.text, None


# === FILES ====================================================================


def _write_generated(path: Path, text: str) -> None:
    """Write a generated file, over an earlier generated one; a file that does not carry the marker is not ours."""
    if path.exists() and MARKER not in path.read_text(encoding="utf-8", errors="replace"):
        raise SceneGenError(f"{path.name} exists and was not generated by mrrsim; move or delete it first")
    path.write_text(text, encoding="utf-8", newline="\n")


def _opening_brace(text: str) -> int:
    """Where the JSONC document's first `{` is, not counting one inside a comment; -1 when there is none."""
    i, n = 0, len(text)
    while i < n:
        if text.startswith("//", i):
            end = text.find("\n", i)
            i = n if end < 0 else end
        elif text.startswith("/*", i):
            end = text.find("*/", i + 2)
            i = n if end < 0 else end + 2
        elif text[i] == "{":
            return i
        else:
            i += 1
    return -1


def _with_header(text: str, note: str) -> str:
    """Put a comment block after the opening brace of a JSONC document."""
    brace = _opening_brace(text)
    if brace < 0:
        return text
    comment = "".join(f"  // {line}\n" for line in note.splitlines())
    return f"{text[:brace + 1]}\n{comment}{text[brace + 1:].lstrip(chr(10))}"


def _robot_config_for(template: str, index: int) -> str:
    """The template robot config with the UDP port pair of vehicle `index`."""
    vp = ports.vehicle_ports(index)
    text, n_in = re.subn(r'("ardupilot-udp-port"\s*:\s*)\d+', rf"\g<1>{vp.sim_in}", template)
    text, n_out = re.subn(r'("local-host-udp-port"\s*:\s*)\d+', rf"\g<1>{vp.sim_out}", text)
    if n_in != 1 or n_out != 1:
        raise SceneGenError(
            "robot config must contain exactly one ardupilot-udp-port and one local-host-udp-port"
        )
    return text


def _write_vehicle_config(config_dir: Path, file_name: str, text: str, template: _Template, index: int,
                          why: str) -> None:
    """Write the robot config of vehicle `index`: `text` with that vehicle's UDP ports, under a header that says
    where it comes from and how to change it."""
    vp = ports.vehicle_ports(index)
    advice = (_design_advice(template.slug) if template.slug is not None
              else f"Edit {template.name} and regenerate instead of editing this file.")
    note = (f"{MARKER} from {template.name}: vehicle {index} (sysid {index + 1}), UDP ports "
            f"{vp.sim_in} / {vp.sim_out}{why}.\n{advice}")
    _write_generated(config_dir / file_name, _with_header(_robot_config_for(text, index), note))


# === PLACEMENT ================================================================


def _offset(xyz: str, index: int, spacing_m: float) -> str:
    """Where vehicle `index` spawns: along y for the first PER_ROW vehicles, then the next row along x."""
    try:
        x, y, z = (float(v) for v in xyz.split())
    except ValueError as exc:
        raise SceneGenError(f'origin xyz "{xyz}" is not three numbers') from exc
    row, column = divmod(index, PER_ROW)
    return " ".join(str(round(v, 9)) for v in (x + spacing_m * row, y + spacing_m * column, z))  # rounded: no 2.1999999999999997


def _placed_origin(origin: dict, base_xyz: str, index: int, spacing_m: float, pose: poseargs.Pose | None) -> dict:
    """The actor origin of vehicle `index`: the scene's own with today's spacing, or as the pose says."""
    placed = dict(origin)
    if pose and index in pose.vehicles:
        x, y, z, roll, pitch, yaw = pose.vehicles[index]
        placed["xyz"] = " ".join(poseargs.fmt(v) for v in (x, y, z))
        rotation = (roll, pitch, yaw)
    else:
        placed["xyz"] = _offset(base_xyz, index, spacing_m)
        rotation = pose.rotation if pose else None
    if pose and (pose.position is not None or index in pose.vehicles):
        placed.pop("geo-point", None)  # a latitude/longitude would win over the position
    if rotation is not None:
        placed["rpy-deg"] = " ".join(poseargs.fmt(v) for v in rotation)
        placed.pop("rpy", None)        # radians would win over degrees
    return placed


# === GENERATING ===============================================================


def _load_template(config_dir: Path, base_scene: str, template_actor: dict,
                   design: tuple[str, dict] | None) -> _Template:
    """The robot config the vehicles are made from: the design, else the one the scene names."""
    if design is not None:
        slug, doc = design
        clean = camerastream.strip(doc)  # the launcher's own camera settings are not the simulator's
        if scenecheck.ardupilot_ports(clean) is None:
            raise SceneGenError(f"the vehicle design {slug!r} has no ArduPilot controller with its UDP ports")
        return _Template(f"robot_design_{slug}.jsonc", slug, _dumps(clean), clean)
    name = template_actor.get("robot-config", "")
    path = config_dir / name
    if not name or not path.is_file():
        raise SceneGenError(f"{base_scene}: robot-config {name or '(missing)'} not found in {config_dir}")
    doc = scenecheck.load_jsonc(path)
    if scenecheck.ardupilot_ports(doc) != (ports.BASE_SIM_IN, ports.BASE_SIM_OUT):
        raise SceneGenError(
            f"{name} must be vehicle 0 (ports {ports.BASE_SIM_IN} / {ports.BASE_SIM_OUT}) to be used as a template"
        )
    return _Template(name, None, path.read_text(encoding="utf-8"), doc)


def _scene_note(base_scene: str, count: int, spacing_m: float, why: str, cameras: bool, resized_to: Size | None,
                slug: str | None, pose: poseargs.Pose | None) -> str:
    """The comment at the top of the generated scene: what it is, where the vehicles spawn, how to change it."""
    layout = f", {spacing_m:g} m apart along y" if count > 1 else ""
    if count > PER_ROW:
        layout += f", {PER_ROW} to a row and the rows {spacing_m:g} m apart along x"
    if slug is not None:
        advice = _design_advice(slug)
    elif pose:  # generate_scene.py cannot place vehicles, so it would not make this scene again
        advice = f"Edit {base_scene} and run again instead of editing this file."
    else:
        command = f"python sim_config/generate_scene.py {count} --base {base_scene}"
        command += f" --spacing {spacing_m:g}" if spacing_m != DEFAULT_SPACING_M else ""
        command += "" if cameras else " --no-cameras"
        command += f" --window {resized_to[0]}x{resized_to[1]}" if resized_to else ""
        advice = f"Edit {base_scene} and regenerate ({command}) instead of editing this file."
    spawn = "".join(f"Spawn pose (--position/--rotation): {line}.\n" for line in (pose.describe(count) if pose else []))
    return f"{MARKER} from {base_scene}: {count} ArduPilot quadrotor(s){layout}{why}.\n{spawn}{advice}"


def generate(
    config_dir: Path,
    base_scene: str,
    count: int,
    spacing_m: float = DEFAULT_SPACING_M,
    cameras: bool = True,
    window: Size | None = None,
    design: tuple[str, dict] | None = None,
    pose: poseargs.Pose | None = None,
) -> str:
    """Write the N-vehicle scene (and the extra robot configs); return the scene file name.

    `window` is the simulator window size. If the template streams a camera feed of another size, the
    copy streams it at the window's size, so Unreal has no reason to resize its window when the vehicle
    spawns. count == 1 with nothing to change returns `base_scene` untouched.

    `design` is (slug, robot config) of a vehicle design to use as the template; see the module docstring.

    `pose` (poseargs.Pose) says where and which way the vehicles spawn instead of the scene's own origin: vehicle 0 at
    `pose.position`, the others spaced from it along y, all turned by `pose.rotation`, except the vehicles in
    `pose.vehicles`, which are placed exactly. A pose always makes a generated scene, named after it.
    """
    if not 1 <= count <= ports.MAX_VEHICLES:
        raise SceneGenError(f"vehicle count {count} out of range 1..{ports.MAX_VEHICLES}")
    if design is None and not pose and count == 1 and cameras \
            and not (window and display_resize_needed(config_dir, base_scene, window)):
        return base_scene

    scene = scenecheck.load_jsonc(config_dir / base_scene)
    robots = _robot_actors(scene)
    if len(robots) != 1:
        raise SceneGenError(
            f"{base_scene} has {len(robots)} robots; the template scene must have exactly one "
            f"(pass --scene to use a hand-made multi-vehicle scene)"
        )
    template_actor = robots[0]
    template = _load_template(config_dir, base_scene, template_actor, design)
    text, resized_to = _adapt_template(template, cameras, window)

    origin = dict(template_actor.get("origin") or {})
    base_xyz = " ".join(poseargs.fmt(v) for v in pose.position) if pose and pose.position is not None \
        else origin.get("xyz", "0 0 0")
    tag = variant_tag(cameras, resized_to)
    why = ", cameras disabled" if not cameras else (
        f", streamed camera resized to the {resized_to[0]}x{resized_to[1]} window" if resized_to else "")
    modified = tag != "" or design is not None  # a design's vehicle 0 is generated too: it is not a file of the scene's
    stem, suffix = Path(template.name).stem, Path(template.name).suffix
    actors = []
    for index in range(count):
        number = index + 1
        placed = _placed_origin(origin, base_xyz, index, spacing_m, pose)
        if index == 0 and not modified:
            # vehicle 0 keeps the original robot config (and the scene's actor, unless a pose moves it)
            actors.append({**template_actor, "origin": placed} if pose else template_actor)
            continue
        config_name = f"{stem}{tag}{f'_{number}' if index else ''}{suffix}"
        _write_vehicle_config(config_dir, config_name, text, template, index, why)
        actors.append({
            **template_actor,
            "name": f"Drone{number}",
            "origin": placed,
            "robot-config": config_name,
        })

    scene["actors"] = [a for a in scene["actors"] if a.get("type") != "robot"] + actors
    name = scene_name(count, cameras, resized_to, template.slug or "", pose)
    note = _scene_note(base_scene, count, spacing_m, why, cameras, resized_to, template.slug, pose)
    _write_generated(config_dir / name, _with_header(_dumps(scene), note))
    problems = scenecheck.check_scene(config_dir, name, count)
    if problems:  # should be impossible; guards against a template the checker reads differently
        raise SceneGenError("generated scene failed its own check: " + "; ".join(problems))
    return name

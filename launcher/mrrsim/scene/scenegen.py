"""Generate a Project AirSim scene with N ArduPilot quadrotors from the single-vehicle scene.

The single-vehicle scene (`[scene] scene`) and its robot config stay the source of truth: clock,
home point and the robot itself are copied from them, so editing those is enough. For N vehicles
this writes, next to the originals:

    scene_ardupilot_<N>quadrotors.jsonc    Drone1..DroneN, spaced along +y
    <robot stem>_<k>.jsonc                 robot config for Drone<k> (k = 2..N), UDP ports of vehicle k-1

Vehicle 0 keeps the original robot config. With cameras=False the same set is written with every
camera sensor disabled, as scene_ardupilot_<N>quadrotors_nocam.jsonc and <robot stem>_nocam[_<k>].jsonc
(also for N = 1); the originals are never changed. Generated files start with a GENERATED marker and are
overwritten on every run; a file without the marker is never touched.

With a `design` (a vehicle made in the Vehicles tab: its slug and its robot-config dict) the design is the template
instead of the robot config named by the scene: every vehicle gets robot_design_<slug>[_<k>].jsonc, vehicle 0 included,
and the scene is scene_ardupilot_<N>quadrotors[...]_design_<slug>.jsonc. Only the UDP ports differ between vehicles.
"""
from __future__ import annotations

import json
import re
from pathlib import Path

from ..core import ports
from . import camerastream, poseargs, scenecheck

MARKER = "GENERATED by mrrsim scenegen"
DEFAULT_SPACING_M = 3.0


class SceneGenError(ValueError):
    pass


Size = tuple[int, int]


def variant_tag(cameras: bool, resized_to: Size | None) -> str:
    """What the generated file names say about how they differ from the originals."""
    if not cameras:
        return "_nocam"
    return f"_{resized_to[0]}x{resized_to[1]}" if resized_to else ""


def scene_name(count: int, cameras: bool = True, resized_to: Size | None = None, design_slug: str = "",
               pose: poseargs.Pose | None = None) -> str:
    design = f"_design_{design_slug}" if design_slug else ""
    placed = f"_{pose.tag()}" if pose else ""   # another pose is another file, so runs with different poses never overwrite
    return f"scene_ardupilot_{count}quadrotors{variant_tag(cameras, resized_to)}{design}{placed}.jsonc"


def streaming_sizes(robot: dict) -> set[Size]:
    """Sizes of the camera feeds Project AirSim streams to the simulator window."""
    return {
        (int(setting["width"]), int(setting["height"]))
        for sensor in robot.get("sensors", [])
        if sensor.get("type") == "camera" and sensor.get("enabled", True)
        for setting in sensor.get("capture-settings", [])
        if setting.get("streaming-enabled") and "width" in setting and "height" in setting
    }


def display_resize_needed(config_dir: Path, scene_file: str, window: Size) -> bool:
    """Would loading this single-vehicle scene make Unreal resize its window?

    When a vehicle spawns, Unreal resizes its window to the size of the camera it streams (and, if its
    remembered mode was fullscreen, goes fullscreen with it). A window of the same size has nothing to
    change. Scenes that cannot be read, or that are not a single-robot template, say False."""
    try:
        scene = scenecheck.load_jsonc(config_dir / scene_file)
        robots = [a for a in scene.get("actors", []) if a.get("type") == "robot"]
        if len(robots) != 1:
            return False
        robot = scenecheck.load_jsonc(config_dir / robots[0].get("robot-config", ""))
    except (scenecheck.SceneParseError, OSError):
        return False
    return any(size != window for size in streaming_sizes(robot))


def _match_streaming(robot: dict, window: Size) -> dict:
    """Make every streamed camera feed the size of the simulator window."""
    for sensor in robot.get("sensors", []):
        if sensor.get("type") == "camera" and sensor.get("enabled", True):
            for setting in sensor.get("capture-settings", []):
                if setting.get("streaming-enabled"):
                    setting["width"], setting["height"] = window
    return robot


def _strip_cameras(robot: dict) -> dict:
    """Disable every camera sensor and its capture/streaming. Other sensors are left alone."""
    for sensor in robot.get("sensors", []):
        if sensor.get("type") == "camera":
            sensor["enabled"] = False
            for setting in sensor.get("capture-settings", []):
                setting["capture-enabled"] = False
                setting["streaming-enabled"] = False
    return robot


def _write_generated(path: Path, text: str) -> None:
    if path.exists() and MARKER not in path.read_text(encoding="utf-8", errors="replace")[:400]:
        raise SceneGenError(f"{path.name} exists and was not generated by mrrsim; move or delete it first")
    path.write_text(text, encoding="utf-8", newline="\n")


def _with_header(text: str, note: str) -> str:
    """Put a comment block after the opening brace of a JSONC document."""
    head, brace, rest = text.partition("{")
    comment = "".join(f"  // {line}\n" for line in note.splitlines())
    return f"{head}{{\n{comment}{rest.lstrip(chr(10))}" if brace else text


def _robot_config_for(template: str, index: int) -> str:
    """The template robot config with the UDP port pair of vehicle `index`."""
    vp = ports.vehicle_ports(index)
    text, n_in = re.subn(r'("ardupilot-udp-port"\s*:\s*)\d+', rf"\g<1>{vp.sim_in}", template)
    text, n_out = re.subn(r'("local-host-udp-port"\s*:\s*)\d+', rf"\g<1>{vp.sim_out}", text)
    if n_in != 1 or n_out != 1:
        raise SceneGenError(
            "robot config must contain exactly one ardupilot-udp-port and one local-host-udp-port"
        )
    return text


def _placed_origin(origin: dict, base_xyz: str, index: int, spacing_m: float, pose: poseargs.Pose | None) -> dict:
    """The actor origin of vehicle `index`: the scene's own with today's spacing, or as the pose says."""
    placed = dict(origin)
    if pose and index in pose.vehicles:
        x, y, z, roll, pitch, yaw = pose.vehicles[index]
        placed["xyz"] = " ".join(poseargs.fmt(v) for v in (x, y, z))
        rotation = (roll, pitch, yaw)
    else:
        placed["xyz"] = _offset(base_xyz, index, spacing_m)
        rotation = pose.rotation if pose else None
    if pose and (pose.position is not None or index in pose.vehicles):
        placed.pop("geo-point", None)  # a latitude/longitude would win over the position
    if rotation is not None:
        placed["rpy-deg"] = " ".join(poseargs.fmt(v) for v in rotation)
        placed.pop("rpy", None)        # radians would win over degrees
    return placed


PER_ROW = 10  # vehicles in a row before the next row starts (so 100 drones are a 10 x 10 block, not a 300 m line)


def _offset(xyz: str, index: int, spacing_m: float) -> str:
    """Where vehicle `index` spawns: along y for the first PER_ROW vehicles, then the next row along x."""
    try:
        x, y, z = (float(v) for v in xyz.split())
    except ValueError as exc:
        raise SceneGenError(f'origin xyz "{xyz}" is not three numbers') from exc
    row, column = divmod(index, PER_ROW)
    return f"{x + spacing_m * row} {y + spacing_m * column} {z}"


def generate(
    config_dir: Path,
    base_scene: str,
    count: int,
    spacing_m: float = DEFAULT_SPACING_M,
    cameras: bool = True,
    window: Size | None = None,
    design: tuple[str, dict] | None = None,
    pose: poseargs.Pose | None = None,
) -> str:
    """Write the N-vehicle scene (and the extra robot configs); return the scene file name.

    `window` is the simulator window size. If the template streams a camera feed of another size, the
    copy streams it at the window's size, so Unreal has no reason to resize its window when the vehicle
    spawns. count == 1 with nothing to change returns `base_scene` untouched.

    `design` is (slug, robot config) of a vehicle design to use as the template; see the module docstring.

    `pose` (poseargs.Pose) says where and which way the vehicles spawn instead of the scene's own origin: vehicle 0 at
    `pose.position`, the others spaced from it along y, all turned by `pose.rotation`, except the vehicles in
    `pose.vehicles`, which are placed exactly. A pose always makes a generated scene, named after it.
    """
    if not 1 <= count <= ports.MAX_VEHICLES:
        raise SceneGenError(f"vehicle count {count} out of range 1..{ports.MAX_VEHICLES}")
    if design is None and not pose and count == 1 and cameras and not (window and display_resize_needed(config_dir, base_scene, window)):
        return base_scene

    scene = scenecheck.load_jsonc(config_dir / base_scene)
    robots = [a for a in scene.get("actors", []) if a.get("type") == "robot"]
    if len(robots) != 1:
        raise SceneGenError(
            f"{base_scene} has {len(robots)} robots; the template scene must have exactly one "
            f"(pass --scene to use a hand-made multi-vehicle scene)"
        )
    template_actor = robots[0]
    design_slug = ""
    if design is not None:
        design_slug, design_doc = design
        robot_name = f"robot_design_{design_slug}.jsonc"
        template_json = camerastream.strip(design_doc)  # the launcher's own camera settings are not the simulator's
        if scenecheck.ardupilot_ports(template_json) is None:
            raise SceneGenError(f"the vehicle design {design_slug!r} has no ArduPilot controller with its UDP ports")
        template = json.dumps(template_json, indent=2) + "\n"
    else:
        robot_name = template_actor.get("robot-config", "")
        robot_path = config_dir / robot_name
        if not robot_name or not robot_path.is_file():
            raise SceneGenError(f"{base_scene}: robot-config {robot_name or '(missing)'} not found in {config_dir}")
        template = robot_path.read_text(encoding="utf-8")
        template_json = scenecheck.load_jsonc(robot_path)
        if scenecheck.ardupilot_ports(template_json) != (ports.BASE_SIM_IN, ports.BASE_SIM_OUT):
            raise SceneGenError(
                f"{robot_name} must be vehicle 0 (ports {ports.BASE_SIM_IN} / {ports.BASE_SIM_OUT}) to be used as a template"
            )
    resized_to = window if (cameras and window and any(s != window for s in streaming_sizes(template_json))) else None
    if not cameras:  # parsed and re-written, so the template's comments are not carried over
        template = json.dumps(_strip_cameras(template_json), indent=2) + "\n"
    elif resized_to:
        template = json.dumps(_match_streaming(template_json, resized_to), indent=2) + "\n"

    origin = dict(template_actor.get("origin") or {})
    base_xyz = origin.get("xyz", "0 0 0")
    path = Path(robot_name)
    tag = variant_tag(cameras, resized_to)
    why = ", cameras disabled" if not cameras else (
        f", streamed camera resized to the {resized_to[0]}x{resized_to[1]} window" if resized_to else "")
    modified = tag != "" or design is not None  # a design's vehicle 0 is generated too: it is not a file of the scene's
    if pose and pose.position is not None:
        base_xyz = " ".join(poseargs.fmt(v) for v in pose.position)
    actors = []
    for index in range(count):
        number = index + 1
        placed = _placed_origin(origin, base_xyz, index, spacing_m, pose)
        if index == 0 and not modified:
            # vehicle 0 keeps the original robot config (and the scene's actor, unless a pose moves it)
            actors.append({**template_actor, "origin": placed} if pose else template_actor)
            continue
        config_name = f"{path.stem}{tag}{f'_{number}' if index else ''}{path.suffix}"
        vp = ports.vehicle_ports(index)
        _write_generated(
            config_dir / config_name,
            _with_header(
                _robot_config_for(template, index),
                f"{MARKER} from {robot_name}: vehicle {index} (sysid {number}), UDP ports "
                f"{vp.sim_in} / {vp.sim_out}{why}.\n"
                + (f"Edit the vehicle design {design_slug!r} in the Vehicles tab and run again instead of editing this file."
                   if design is not None else f"Edit {robot_name} and regenerate instead of editing this file."),
            ),
        )
        actors.append({
            **template_actor,
            "name": f"Drone{number}",
            "origin": placed,
            "robot-config": config_name,
        })

    scene["actors"] = [a for a in scene["actors"] if a.get("type") != "robot"] + actors
    name = scene_name(count, cameras, resized_to, design_slug, pose)
    _write_generated(
        config_dir / name,
        _with_header(
            json.dumps(scene, indent=2) + "\n",
            f"{MARKER} from {base_scene}: {count} ArduPilot quadrotor(s), {spacing_m:g} m apart along y{why}.\n"
            + "".join(f"Spawn pose (--position/--rotation): {line}.\n" for line in (pose.describe(count) if pose else []))
            + (f"Edit the vehicle design {design_slug!r} in the Vehicles tab and run again instead of editing this file."
             if design is not None else
             f"Edit {base_scene} and regenerate (python sim_config/generate_scene.py {count}"
             f"{'' if cameras else ' --no-cameras'}{f' --window {resized_to[0]}x{resized_to[1]}' if resized_to else ''}) "
             f"instead of editing this file."),
        ),
    )
    problems = scenecheck.check_scene(config_dir, name, count)
    if problems:  # should be impossible; guards against a template the checker reads differently
        raise SceneGenError("generated scene failed its own check: " + "; ".join(problems))
    return name
